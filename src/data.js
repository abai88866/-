export function generateCandles() {
  return Array.from({ length: 62 }, (_, i) => {
    const base = 72 + Math.sin(i / 4) * 18 + Math.sin(i / 9) * 10;
    const open = base + Math.sin(i * 1.8) * 7;
    const close = base + Math.cos(i * 1.35) * 8;
    return { x: 18 + i * 15, open, close, high: Math.max(open, close) + 8 + (i % 5), low: Math.min(open, close) - 7 - (i % 4) };
  });
}
